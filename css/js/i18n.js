// ========== i18n HELPER ==========
function T(key, fallback) {
    var t = (typeof translations !== 'undefined' ? translations[currentLang] : null) || (typeof translations !== 'undefined' ? translations.en : null) || {};
    return t[key] || fallback || key;
}

function detectLang() {
    var bl = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (bl.startsWith('ko')) return 'ko';
    if (bl.startsWith('zh')) return 'zh';
    if (bl.startsWith('ru')) return 'ru';
    if (bl.startsWith('th')) return 'th';
    if (bl.startsWith('vi')) return 'vi';
    if (bl.startsWith('ja')) return 'ja';
    if (bl.startsWith('de')) return 'de';
    if (bl.startsWith('fr')) return 'fr';
    if (bl.startsWith('es')) return 'es';
    return 'en';
}

function applyLang(lang) {
    currentLang = lang;
    var t = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var key = el.getAttribute('data-i18n');
        if (t[key]) el.textContent = t[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
        var key = el.getAttribute('data-i18n-html');
        if (t[key]) el.innerHTML = t[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) el.placeholder = t[key];
    });
    var sel = document.getElementById('lang-select');
    if (sel) sel.value = lang;
    try { localStorage.setItem('feeslash_lang', lang); } catch (e) { }
    try { loadFaqForLang(lang); } catch (e) { }
    try { tickerTimeText = tickerTimeTexts[lang] || tickerTimeTexts.en; } catch (e) { }
    try { updateEnergyPrice(); } catch (e) { }
}

window.setLang = function (lang) { applyLang(lang); };